// Чистые функции без данных — общие для индекса (названия улиц и пунктов) и разбора запроса.

import { switchLayout } from "@/lib/search/text";

/**
 * Текст как набран → без невидимых знаков: мягкий перенос и пробел нулевой ширины при копировании с сайта
 * («Крас\u00ADная»), полноширинные цифры и латиница («Красная１２０») → обычные.
 */
export function cleanText(s: string): string {
  return s
    .normalize("NFC")
    .replace(/[\u00AD\u200B-\u200F\u2060\uFEFF]/g, "")
    .replace(/[\uFF01-\uFF5E]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .replace(/\u3000/g, " ");
}

/** Нижний регистр, ё→е, латинские двойники в кириллице не трогаем (это делает разбор номера). */
export function fold(s: string): string {
  return cleanText(s).toLowerCase().replace(/ё/g, "е");
}

