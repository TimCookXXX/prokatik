import { monotonicFactory, ulid } from "ulid";

export function newId(): string {
  return ulid();
}

// ULID с временем `ms`, а не текущим: в id зашито время создания, и id,
// выданный сейчас, выдавал бы момент, который строка не должна раскрывать.
export function newIdAt(ms: number): string {
  return ulid(ms);
}

// Монотонный ULID — для сущностей, у которых id служит ключом сортировки и
// курсором пагинации. Обычный ulid() внутри одной миллисекунды даёт случайный
// хвост, и два сообщения, отправленные подряд, могут разъехаться по порядку:
// лента показала бы их не в том порядке, а курсор «всё, что новее X» — пропустил
// бы соседа. Сейчас это сообщения чата.
//
// Монотонность держится в пределах процесса. При нескольких инстансах гарантия
// вырождается до обычного ULID, но и тогда расходятся только сообщения одной
// миллисекунды в одном треде — то есть практически только двойная отправка.
const monotonic = monotonicFactory();

export function newSortableId(): string {
  return monotonic();
}
