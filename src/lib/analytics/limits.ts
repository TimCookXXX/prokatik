// Числа своей статистики посещений. Политика конфиденциальности и документация
// ссылаются на эти константы, а не повторяют их: срок, названный людям, и срок,
// по которому чистит код, не могут разойтись.

/** Сколько дней хранится событие браузера: страница, поиск, просмотр. */
export const EVENT_RETENTION_DAYS = 180;

/** Через сколько дней без активности удаляется сама карточка браузера. */
export const VISITOR_RETENTION_DAYS = 400;

/**
 * Сколько живут резервные копии базы: правило lifecycle холодного бакета
 * (docs/DEPLOY.md, «Бакет для бэкапов»). Удалённое из базы остаётся в копиях
 * до этого срока — политика говорит об этом прямо. Код по нему не чистит.
 */
export const BACKUP_RETENTION_DAYS = 30;

/**
 * Сколько событий за московские сутки принимает роут сбора на весь сайт.
 * Сверх него события отбрасываются до следующих суток: потолок держит рост
 * таблицы и дампов бэкапа, если сбор начнут заливать мусором. Нынешний трафик
 * до него не доходит с большим запасом.
 */
export const DAILY_EVENT_CAP = 10_000;

/** Сколько событий трекер отправляет одной пачкой. */
export const TRACK_BATCH_MAX = 10;

/** Потолок тела пачки: роут читает с отсечкой и дальше не разбирает. */
export const TRACK_BODY_MAX_BYTES = 8 * 1024;

/** Длина адреса и referrer'а, как их шлёт браузер; трекер режет до неё сам. */
export const TRACK_RAW_PATH_MAX = 1000;

/**
 * Сколько часов действует подписанный токен страницы (lib/analytics/token.ts).
 * Сутки, а не минуты: «Забронировать» шлётся с токеном открытой страницы, а
 * вкладку держат открытой долго.
 */
export const TRACK_TOKEN_TTL_HOURS = 24;

/** Длина подписанного токена страницы в пачке. */
export const TRACK_TOKEN_MAX = 3000;
