function street(id: string, placeId: string, name: string, type: string, lat: number, lon: number, nums: string[], aliases: string[] = []) {
  streets.push({ id, placeId, name, type, aliases, lat, lon, houses: nums.length });
  nums.forEach((number, i) => {
    const n = parseInt(number, 10) || i;
    houses.push({ streetId: id, placeId, number, lat: lat + (n % 2 ? 0.0002 : -0.0002), lon: lon + (n % 50) * 0.00025, precision: "house", source: "osm" });
  });
}

function placeHouses(placeId: string, lat: number, lon: number, nums: string[]) {
  for (const number of nums) houses.push({ streetId: null, placeId, number, lat, lon, precision: "place", source: "gar" });
}

