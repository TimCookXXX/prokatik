const DATA: GeoIndexData = { version: "test", citySlug: "krasnodar", builtAt: "2026-09-30T00:00:00Z", places, streets, houses, pois };
const g = createGeocoder(DATA);
const near = { lat: 45.0355, lon: 38.9753 };
const list = (q: string) => g.suggest(q, { near }).map((h) => `${h.title} — ${h.subtitle}`);
const line = (q: string) => list(q)[0] ?? null;
const geoHit = (q: string) => g.geocode(q, { near });
const geo = (q: string) => {
  const h = geoHit(q);
  return h ? `${h.title} — ${h.subtitle}` : null;
};

describe("тип улицы назван явно", () => {
  it("«д.» перед номером — метка номера, а не буква названия «проезд им. Д. Ковтюха»", () => {
    for (const q of ["Краснодар, проезд Ковтюха, д. 144", "Краснодар, пр-д Ковтюха, д. 144", "Краснодар, Ковтюха проезд, д. 144", "Краснодар, проезд Ковтюха, 144"]) {
      expect(line(q), q).toBe("проезд Ковтюха, 144 — Краснодар");
      expect(geo(q), q).toBe("проезд Ковтюха, 144 — Краснодар");
    }
  });

  it("улица-тёзка другого типа — не соперник для импорта", () => {
    expect(geo("г. Краснодар, проезд Кропоткина, 15")).toBe("проезд Кропоткина, 15 — Краснодар");
    expect(geo("г. Краснодар, проезд Кропоткина, д. 15")).toBe("проезд Кропоткина, 15 — Краснодар");
    // тип не назван — неоднозначно, как и было
    expect(geo("г. Краснодар, Кропоткина, 15")).toBeNull();
  });
});

describe("тёзки в одном городе", () => {
  it("почтовый индекс выбирает дом", () => {
    const h = geoHit("350912, г. Краснодар, ул. Дзержинского, д. 25");
    expect(h?.title).toBe("улица Дзержинского, 25");
    expect(h?.lat).toBeCloseTo(45.0328, 3);
    expect(h?.subtitle).toBe("Краснодар, Комсомольский");
    expect(geoHit("350058, г. Краснодар, ул. Дзержинского, д. 25")?.lat).toBeCloseTo(45.0579, 3);
  });

  it("два настоящих дома в названном городе без индекса и микрорайона — отказ", () => {
    expect(g.geocodeDetailed("г. Краснодар, улица Дзержинского, д. 37", { near }).reason).toBe("ambiguous_place");
    const top = list("г. Краснодар, улица Дзержинского, д. 37");
    expect(top[0]).toMatch(/^улица Дзержинского, 37 — Краснодар/);
    expect(top[1]).toBe("улица Дзержинского, 37 — Краснодар, Комсомольский");
  });

  it("микрорайон, названный вместе с городом, выбирает тёзку в нём", () => {
    expect(line("Краснодар, КМР, ул. Дзержинского, 38")).toBe("улица Дзержинского, 38 — Краснодар, Комсомольский");
    expect(geoHit("Краснодар, КМР, ул. Дзержинского, 38")?.lat).toBeCloseTo(45.0327, 3);
  });
});

