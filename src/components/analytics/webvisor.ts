// Классы, которыми Вебвизор Метрики узнаёт, что записывать нельзя. Правило
// класса действует на сам элемент и на всех потомков.
//   ym-hide-content — текст в записи размыт, картинки серые;
//   ym-disable-keys — содержимое полей ввода заменено звёздочками.
// Портал (окно, шторка, меню, всплывашка) выходит из DOM-обёртки личной зоны,
// поэтому личное содержимое в портале помечается отдельно.

/** Личная зона целиком: кабинет, переписка, профиль, админка, вход. */
export const WEBVISOR_PRIVATE = "ym-hide-content ym-disable-keys";

/** Форма с телефоном, паролем или почтой на публичной странице. */
export const WEBVISOR_NO_KEYS = "ym-disable-keys";
