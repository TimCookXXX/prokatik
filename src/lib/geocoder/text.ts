// Обратный транслит под то, как пишут адреса латиницей: «ulitsa Krasnaya», «Stavropolskaya», «Pervomayskiy».
const LAT_MULTI: [string, string][] = [
  ["shch", "щ"], ["sch", "щ"], ["tch", "ч"], ["zh", "ж"], ["kh", "х"], ["ts", "ц"], ["tz", "ц"], ["ch", "ч"], ["sh", "ш"],
  ["yu", "ю"], ["ya", "я"], ["yo", "е"], ["ye", "е"], ["iy", "ий"], ["yy", "ый"], ["ja", "я"], ["ju", "ю"],
];
const LAT_VOWELS = /[aeiouy]/;
const LAT_ONE: Record<string, string> = {
  a: "а", b: "б", v: "в", g: "г", d: "д", e: "е", z: "з", i: "и", y: "ы", k: "к", l: "л", m: "м", n: "н",
  o: "о", p: "п", r: "р", s: "с", t: "т", u: "у", f: "ф", h: "х", c: "ц", w: "в", x: "кс", j: "й", q: "к",
  "'": "ь",
};

/** Транслит как в загранпаспорте (ICAO): я = ia, ю = iu, ий = ii, ый = yi («Slavianskaia», «Iuzhnyi»). */
export const ICAO_LATIN = /ia|iu|ii|yi/;

/**
 * «krasnaya» → «красная», «ulitsa» → «улица», «Pervomayskiy» → «первомайский».
 * `icao` — сначала сочетания паспортного транслита: «slavianskaia» → «славянская», «iablonovskii» → «яблоновский».
 */
export function translitToRu(s: string, icao = false): string {
  let src = s.toLowerCase();
  if (icao) {
    src = src
      .replace(/iia/g, "ия").replace(/iiu/g, "ию").replace(/ii(?![a-z])/g, "ий").replace(/yi(?![a-z])/g, "ый")
      .replace(/ia/g, "я").replace(/iu/g, "ю");
  }
  // порядковые: «5-y», «2-ya», «1-e» → «5-й», «2-я», «1-е»
  const low = src
    .replace(/(\d)-(?:y|iy|yy|oy|iy)(?![a-z])/g, "$1-й")
    .replace(/(\d)-(?:ya|aya)(?![a-z])/g, "$1-я")
    .replace(/(\d)-(?:e|oe|ye)(?![a-z])/g, "$1-е")
    .replace(/(\d)-(?:go|ogo)(?![a-z])/g, "$1-го");
  let out = "";
  for (let i = 0; i < low.length;) {
    const multi = LAT_MULTI.find(([lat]) => low.startsWith(lat, i));
    if (multi) {
      out += multi[1];
      i += multi[0].length;
      continue;
    }
    const c = low[i];
    // «y» после гласной — «й» («Pervomayskiy», «Stanovoy»), иначе «ы» («Kryma»)
    if (c === "y" && i > 0 && LAT_VOWELS.test(low[i - 1])) out += "й";
    else out += LAT_ONE[c] ?? c;
    i++;
  }
  return out;
}

/** Латинские двойники кириллицы в номере дома: «78/1A» → «78/1а», «12B» → «12в». */
const LOOKALIKE: Record<string, string> = { a: "а", b: "в", c: "с", e: "е", k: "к", m: "м", h: "н", o: "о", p: "р", t: "т", x: "х", y: "у" };
export function lookalikesToRu(s: string): string {
  return s.replace(/[abcekmhoptxy]/g, (c) => LOOKALIKE[c] ?? c);
}

/**
 * Слово набрано вперемешку латинскими двойниками и кириллицей («KPACHAЯ», «HOBOPOCCИЙCKAЯ», «кpacнaя») или
 * целиком заглавными двойниками («MOCKOBCKAЯ» без «Я» — «MOCKOBCKA») — двойники в кириллицу.
 * `raw` — кусок как набран (регистр важен: заглавные B, H, M, T, K похожи на В, Н, М, Т, К, строчные — нет).
 */
export function homoglyphsToRu(raw: string): string | null {
  const s = raw.normalize("NFC");
  if (!/[a-z]/i.test(s)) return null;
  const cyr = /[а-яё]/i.test(s);
  const caps = s === s.toUpperCase();
  // латиница только из двойников: заглавные — все, строчные — те, что пишутся так же (a, c, e, o, p, x, y)
  const letters = s.match(/[a-z]/gi) ?? [];
  const ok = letters.every((c) => (c === c.toUpperCase() ? "ABCEHKMOPTXY".includes(c) : "aceopxy".includes(c)));
  if (!ok || (!cyr && !caps)) return null;
  return fold(s).replace(/[abcekmhoptxy]/g, (c) => LOOKALIKE[c] ?? c);
}

/**
 * Латинское название объекта кириллицей — как его произносят и набирают по-русски: «Oz Mall» → «оз молл»,
 * «Royal City Mall» → «роял сити молл», «Salam city» → «салам сити», «SuperStep» → «суперстеп».
 * Грубые правила английского чтения поверх транслита; нужна только похожесть (дальше — опечатки и фонетика).
 */
export function latinNameToRu(s: string): string {
  const low = s.toLowerCase()
    .replace(/all(?![a-z])/g, "олл")      // mall, hall
    .replace(/ck/g, "к").replace(/ph/g, "ф").replace(/th/g, "т").replace(/oo/g, "у").replace(/ee/g, "и")
    .replace(/c(?=[eiy])/g, "с").replace(/y(?![a-z])/g, "и").replace(/^j|(?<=[^a-z])j/g, "дж")
    .replace(/w/g, "у").replace(/qu/g, "кв");
  return translitToRu(low);
}

