// Не та раскладка: вместе с буквами меняются и знаки на месте русских букв (`,` = «б», `;` = «ж», `[` = «х»).
// Shift-символы (`{`, `:`, `<`…) — заглавные «Х», «Ж», «Б». Цифры и `/` остаются.
const EN_KEYS = "`qwertyuiop[]asdfghjkl;'zxcvbnm,.";
const RU_KEYS = "ейцукенгшщзхъфывапролджэячсмитьбю";
const EN_TO_RU: Record<string, string> = { "{": "х", "}": "ъ", ":": "ж", '"': "э", "<": "б", ">": "ю", "~": "е" };
for (let i = 0; i < EN_KEYS.length; i++) EN_TO_RU[EN_KEYS[i]] = RU_KEYS[i];

/** «,fpjdcrfz» → «базовская», «Rhfcyfz» → «красная». Только EN → RU (обратное — `switchLayout` сравнения). */
export function layoutToRu(s: string, keepPunct = false): string {
  let out = "";
  for (const c of s.toLowerCase()) out += keepPunct && (c === "." || c === ",") ? c : EN_TO_RU[c] ?? c;
  return out;
}

