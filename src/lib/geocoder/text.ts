/**
 * «Семидесятилетия», «пятидесятилетия», «двадцатипятилетия», «столетия» → число лет («70»): «улица 70 лет Октября».
 * `null` — не такое слово.
 */
export function yearsWord(w: string): string | null {
  const m = /^([а-я]+?)(?:летия|летию|летие|летнего|летний|лет)$/.exec(w);
  if (!m) return null;
  let rest = m[1];
  let n = 0;
  for (const [stem, v] of YEAR_TENS) {
    if (rest.startsWith(stem)) {
      n += v;
      rest = rest.slice(stem.length);
      break;
    }
  }
  for (const [stem, v] of YEAR_UNITS) {
    if (rest === stem) {
      n += v;
      rest = "";
      break;
    }
  }
  return n > 0 && !rest ? String(n) : null;
}
