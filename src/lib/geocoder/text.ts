export function functionKind(w: string): FunctionKind | null {
  if (w in STREET_TYPES) return "street-type";
  // сокращение микрорайона, которого нет в справочнике («ЦМР», «ВКМР»): не название улицы и не опечатка другого
  // («КМР»), а уточнение места — как «район»; известные («ЮМР», «КМР») находятся точным совпадением
  if (/^[бвгджзклмнпрстфхцчшщ]{1,3}мр$/.test(w)) return "filler";
  if (w in PLACE_TYPES) return "place-type";
  if (REGION.has(w)) return "region";
  if (HOUSE_WORDS.has(w)) return "house";
  if (APARTMENT_WORDS.has(w)) return "apartment";
  if (TITLES.has(w)) return "title";
  if (FILLERS.has(w) || POI_TYPES.has(w)) return "filler";
  return null;
}

/** Канонический тип улицы по слову («пр-т» → «проспект»); `null` — не тип. */
export function streetTypeOf(w: string): string | null {
  return STREET_TYPES[w] ?? null;
}

// ------------------------------------------------------------------ числительные

const ORDINAL_WORDS: Record<string, string> = {
  перв: "1", втор: "2", трет: "3", четверт: "4", пят: "5", шест: "6", седьм: "7", восьм: "8", девят: "9", десят: "10",
  одиннадцат: "11", двенадцат: "12", тринадцат: "13", четырнадцат: "14", пятнадцат: "15", шестнадцат: "16",
  семнадцат: "17", восемнадцат: "18", девятнадцат: "19", двадцат: "20", тридцат: "30", сороков: "40", пятидесят: "50",
  шестидесят: "60", семидесят: "70", восьмидесят: "80", девяност: "90", сот: "100",
};
const CARDINAL_WORDS: Record<string, string> = {
  один: "1", два: "2", три: "3", четыре: "4", пять: "5", шесть: "6", семь: "7", восемь: "8", девять: "9", десять: "10",
  двадцать: "20", тридцать: "30", сорок: "40", пятьдесят: "50", шестьдесят: "60", семьдесят: "70", восемьдесят: "80",
  девяносто: "90", сто: "100",
};
const ORD_END = /^(ый|ий|ой|ая|яя|ое|ее|ого|его|ому|ему|ым|им|ом|ем|ую|юю|ые|ие|ых|их|ой|ей)$/;

/** «первого», «первая», «1-го» → «1»; «сорок» → «40». `null` — не числительное. */
export function numeralWord(w: string): string | null {
  if (w in CARDINAL_WORDS) return CARDINAL_WORDS[w];
  for (const [stem, n] of Object.entries(ORDINAL_WORDS)) {
    if (w.startsWith(stem) && ORD_END.test(w.slice(stem.length))) return n;
  }
  return null;
}

/** Нормальная форма слова названия: «летия» → «лет» («40-летия Победы» = «40 лет Победы»). */
export function canonicalWord(w: string): string {
  if (w === "летия" || w === "летию" || w === "летие") return "лет";
  // общепринятое сокращение города («Крд, Красная 120»)
  if (w === "крд") return "краснодар";
  return w;
}

// ------------------------------------------------------------------ падежи и фонетика

// Окончания прилагательных и существительных: «Красной» / «Красную» / «Красная» → «красн»,
// «Ставропольской» → «ставропольск», «Ростовском» → «ростовск».
const ENDINGS = [
  "ыми", "ими", "ого", "его", "ому", "ему", "ая", "яя", "ой", "ей", "ую", "юю", "ый", "ий", "ое", "ее", "ые", "ие",
  "ых", "их", "ым", "им", "ом", "ем", "ам", "ям", "ах", "ях", "а", "я", "ы", "и", "у", "ю", "е", "о",
];

/** Грубая основа: окончание прочь, если остаётся не меньше 3 букв. Для чисел и коротких слов — как есть. */
export function stemWord(w: string): string {
  if (w.length < 5 || !/^[а-я]+$/.test(w)) return w;
  for (const e of ENDINGS) if (w.endsWith(e) && w.length - e.length >= 3) return w.slice(0, -e.length);
  return w;
}

/** Фонетический ключ: безударные гласные, двойные согласные, ь/ъ, «тс»→«ц» — «Кутузава» = «Кутузова». */
export function phoneticKey(w: string): string {
  if (!/[а-я]/.test(w)) return w;
  return w
    // «-ого» читается «-ова»: «Горкова» = «Горького», «Толстова» = «Толстого»
    .replace(/([ое])го$/, "$1во")
    .replace(/[ьъ]/g, "")
    .replace(/тс|дс/g, "ц")
    .replace(/[оа]/g, "а")
    .replace(/[еиыяэй]/g, "и")
    .replace(/[юу]/g, "у")
    .replace(/(.)\1+/g, "$1");
}

// ------------------------------------------------------------------ слова названий

/** Слова названия для индекса: «улица имени 40-летия Победы» → «40», «лет», «победы» (тип и «имени» — отдельно). */
export function nameWords(name: string): string[] {
  const s = fold(name)
    .replace(/(\d+)\s*-?\s*(?:ый|ий|ой|ая|яя|ое|ее|го|ого|его|му|ому|ему|ом|ем|й|я|е|м|х|ых|ти)(?![а-я])/g, "$1 ")
    .replace(/(\d+)\s*-?\s*(летия|летию|летие|лет)/g, "$1 лет")
    .replace(/[«»"„“”'`]/g, "")
    .replace(/(\d)([а-я])/g, "$1 $2")
    .replace(/([а-я])(\d)/g, "$1 $2");
  return s
    .split(/[^0-9a-zа-я]+/)
    .filter(Boolean)
    .map((w) => numeralWord(w) ?? canonicalWord(w));
}

/** Дефис внутри названия — слитно: «Кубано-Набережная» → «кубанонабережная» (в индексе есть обе формы). */
export function joinHyphens(s: string): string {
  return s.replace(/([а-яё]{2,})-(?=[а-яё]{2,})/gi, "$1");
}
