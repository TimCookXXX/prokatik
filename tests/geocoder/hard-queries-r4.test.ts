/** Улица с домами: номер → [широта, долгота, индекс?]; точка улицы — у первого дома. */
function street(id: string, placeId: string, name: string, type: string, list: [string, number, number, string?][], aliases: string[] = []) {
  streets.push({ id, placeId, name, type, aliases, lat: list[0][1], lon: list[0][2], houses: list.length });
  for (const [number, lat, lon, postcode] of list) houses.push({ streetId: id, placeId, number, lat, lon, precision: "house", source: "osm", postcode: postcode ?? null });
}
/** Ряд домов вдоль улицы (главная улица — много домов). */
const row = (lat: number, lon: number, nums: string[], postcode?: string): [string, number, number, string?][] =>
  nums.map((n, i) => [n, lat + i * 0.0003, lon + i * 0.0003, postcode]);

